#!/bin/sh
# Regenerates vectors.txt from a wendy-lite checkout.
# Usage: gen.sh <path to wendy-lite>
set -e
lite=${1:?path to wendy-lite}
here=$(cd "$(dirname "$0")" && pwd)
c=$lite/components
out=$(mktemp -d)
cc -std=c11 -D_DEFAULT_SOURCE -Wall -o "$out/gen" "$here/cgen/gen.c" \
	-I"$here/cgen/stub" -I"$c/wendy_net_peer/include" -I"$c/wendy_net_common/include" \
	-I"$c/wendy_net_gossip/include" -I"$c/wendy_pki/include" \
	"$c/wendy_net_common/src/binary.c" "$c/wendy_net_peer/src/binary.c" \
	"$c/wendy_net_peer/src/protocol.c" "$c/wendy_net_peer/src/packet.c" \
	"$c/wendy_net_peer/src/control.c" "$c/wendy_net_gossip/src/gossip.c"
{
	echo "# Generated by gen.sh from wendy-lite $(git -C "$lite" rev-parse --short HEAD). Do not edit."
	"$out/gen"
} > "$here/vectors.txt"
rm -rf "$out"
